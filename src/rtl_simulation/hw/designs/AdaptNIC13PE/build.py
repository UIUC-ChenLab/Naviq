#!/usr/bin/env python3
"""Build the copied 13-PE snapshot using Naviq's existing RTL builder."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

HERE = Path(__file__).resolve().parent
RTL = HERE.parents[2]
NAVI = RTL.parents[1]


def class_name(name):
    return 'Pe13' + ''.join(x.capitalize() for x in name.split('_')) + 'RtlNode'


def generate(instance):
    model = 'pe13_' + instance['name']
    output = RTL / 'build' / model
    discovered = json.loads((output / (model + '_noc_endpoints.json')).read_text())
    expected = instance['endpoints']
    physical = [e for e in expected if e.get('transport', 'noc') == 'noc']
    by_path = {e['instance_path']: e for e in discovered['endpoints']}
    if set(by_path) != {e['instance_path'] for e in physical}:
        raise ValueError(f'{model}: endpoint mismatch')
    bindings = []
    direct_traits = []
    widths = []
    root_header = (output / f'{model}___024root.h').read_text()

    def check_width(signal, expected_width):
        # Public XPM nets carry Verilator's bit-range comment. Plain top ports
        # use VL_IN*/VL_OUT* declarations instead. Validate actual elaboration.
        escaped = re.escape(signal)
        match = re.search(r'/\*(\d+):(\d+)\*/\s+' + escaped + r'\s*;', root_header)
        if not match:
            match = re.search(r'VL_(?:IN|OUT|INOUT)\w*\(' + escaped +
                              r',\s*(\d+),\s*(\d+)(?:,|\))', root_header)
        if not match or int(match[1]) - int(match[2]) + 1 != expected_width:
            raise ValueError(f'{model}: expected {signal} width {expected_width}, declaration {match}')

    for e in expected:
        if e.get('transport') == 'direct':
            if e['protocol'] != 'axis':
                raise ValueError(f'{model}: direct endpoint must be AXIS')
            prefix = e['flat_prefix']
            trait_name = f'Axis_Local_{prefix}Traits'
            accessors = []
            for signal, width in [('tdata', 512), ('tkeep', 64), ('tid', 6),
                                  ('tdest', 10), ('tlast', 1), ('tvalid', 1), ('tready', 1),
                                  ('tuser', 1)]:
                check_width(prefix + '_' + signal, width)
                accessors.append(f'    template <typename RootT> static constexpr auto& {signal}_ref(RootT& r) {{ return r.{prefix}_{signal}; }}')
            direct_traits.append('struct ' + trait_name + ' {\n' + '\n'.join(accessors) + '\n};')
            bindings.append(f"        this->template bindAxis<{model}_verilator::{trait_name}, true>({'true' if e['role']=='nsu' else 'false'});")
            widths.append(dict(name=e['name'], transport='direct', data_width=512, tid_width=6, tdest_width=10, tuser_width=1))
            continue
        actual = by_path[e['instance_path']]
        if (actual['protocol'], actual['role']) != (e['protocol'], e['role']):
            raise ValueError(f'{model}: endpoint direction mismatch')
        if e['protocol'] == 'axis':
            trait = f"{model}_verilator::Axis_{actual['verilator_path']}Traits"
            bindings.append(f"        this->template bindAxis<{trait}>({'true' if e['role']=='nsu' else 'false'});")
            for signal, width in [('tdata', 512), ('tkeep', 64), ('tid', 6),
                                  ('tdest', 10), ('tlast', 1), ('tvalid', 1), ('tready', 1)]:
                check_width(actual['verilator_path'] + '__DOT__' + actual['signal_prefix'] + signal, width)
            widths.append(dict(name=e['name'], transport='noc', data_width=512, tid_width=6, tdest_width=10))
        else:
            trait = f"{model}_verilator::Axi_{actual['verilator_path']}Traits"
            bindings.append(f'        this->template bindControl<{trait}>();')
            for signal, width in [('awaddr', 64), ('araddr', 64), ('wdata', 32), ('rdata', 32),
                                  ('wstrb', 4), ('awid', 2), ('arid', 2)]:
                check_width(actual['verilator_path'] + '__DOT__' + actual['signal_prefix'] + signal, width)
            widths.append(dict(name=e['name'], transport='noc', data_width=32, address_width=64, id_width=2))
    cls = class_name(instance['name'])
    header = f'''// Generated by AdaptNIC13PE/build.py from validated XPM and direct ports.
#pragma once
#include "{model}.h"
#include "{model}___024root.h"
#include "{model}_verilator_mappings.h"
#include "noc/endpoints/rtl/Pe13RtlNode.hh"
#include "params/{cls}.hh"
namespace {model}_verilator {{
{chr(10).join(direct_traits)}
}}
namespace gem5::noc {{
class {cls} : public Pe13RtlNode<{model}, {cls}Params> {{
  public:
    explicit {cls}(const {cls}Params &p) : Pe13RtlNode(p) {{
{chr(10).join(bindings)}
        this->finishBindings();
    }}
}};
}}
'''
    py = f'''# Generated by AdaptNIC13PE/build.py.
from m5.params import *
from m5.proxy import *
from m5.objects.NocNode import NocNode
from m5.SimObject import PyBindMethod

class {cls}(NocNode):
    type = "{cls}"
    cxx_header = "noc/endpoints/rtl/generated/{cls}.hh"
    cxx_class = "gem5::noc::{cls}"
    cxx_exports = [PyBindMethod("packetCounts"), PyBindMethod("packetTidMasks"), PyBindMethod("portTrafficCounts"), PyBindMethod("hasOutstandingTransactions")]
    noc_system = Param.NocSystem(Parent.any, "NoC system")
    control_base = Param.UInt64({instance.get('control_aperture', {}).get('start', 0)}, "Global MMIO aperture; unused for host fabric")
    reset_cycles = Param.UInt32(16, "PE reset cycles")
    data_width = Param.UInt32(512, "AXIS data width")
    tid_width = Param.UInt32(6, "AXIS ID width")
    tdest_width = Param.UInt32(10, "AXIS destination width")
'''
    dest = NAVI / 'src/noc/endpoints/rtl/generated'
    dest.mkdir(parents=True, exist_ok=True)
    for suffix, text in (('.hh', header), ('.py', py)):
        file = dest / (cls + suffix)
        if not file.exists() or file.read_text() != text:
            file.write_text(text)
    return dict(name=instance['name'], model=model, parameters=instance['parameters'], ports=widths,
                control_aperture=instance.get('control_aperture'))


def build(instance, generate_only):
    manifest = HERE / (instance['name'] + '.rtl.json')
    spec = json.loads(manifest.read_text())
    stamp = RTL / 'build' / spec['design'] / 'verilated.stamp'
    inputs = [manifest, RTL / 'build_rtl_models.py', *[(HERE / s).resolve() for s in spec['sources']]]
    inputs += list((HERE / 'snapshot').rglob('*.svh'))
    for path in inputs:
        if not path.is_relative_to(NAVI) or not path.is_file():
            raise ValueError(f'{manifest}: source outside Naviq or missing: {path}')
    for include in spec.get('include_dirs', []):
        path = (HERE / include).resolve()
        if not path.is_relative_to(NAVI) or not path.is_dir():
            raise ValueError(f'{manifest}: include outside Naviq or missing: {path}')
    if not generate_only and (not stamp.exists() or any(p.stat().st_mtime > stamp.stat().st_mtime for p in inputs)):
        log = HERE / 'build_logs' / (instance['name'] + '.log')
        log.parent.mkdir(parents=True, exist_ok=True)
        print(f"Building {instance['name']} (log: {log})", flush=True)
        with log.open('w') as stream:
            result = subprocess.run([sys.executable, str(RTL / 'build_rtl_models.py'), '--manifest', str(manifest)],
                                    stdout=stream, stderr=subprocess.STDOUT)
        if result.returncode:
            raise RuntimeError(f"{instance['name']} Verilation failed; see {log}")
    result = generate(instance)
    print(f"Validated {instance['name']}: {len(result['ports'])} ports", flush=True)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate-only', action='store_true')
    parser.add_argument('--jobs', type=int, default=1, help='Independent Verilator processes')
    parser.add_argument('--models', nargs='+', help='Build selected PE names or host_fabric')
    args = parser.parse_args()
    instances = json.loads((HERE / 'instances.json').read_text())
    if (HERE / 'host_fabric.instance.json').exists():
        instances.append(json.loads((HERE / 'host_fabric.instance.json').read_text()))
    if args.models:
        unknown = set(args.models) - {instance['name'] for instance in instances}
        if unknown:
            parser.error('Unknown models: ' + ', '.join(sorted(unknown)))
        instances = [instance for instance in instances if instance['name'] in args.models]
    if args.jobs < 1:
        parser.error('--jobs must be positive')
    for relative, source in json.loads((HERE / 'SOURCES.json').read_text()).items():
        if hashlib.sha256((HERE / relative).read_bytes()).hexdigest() != source.get('snapshot_sha256', source['sha256']):
            raise ValueError(f'Snapshot provenance hash mismatch: {relative}')
    with ThreadPoolExecutor(max_workers=args.jobs) as executor:
        results = list(executor.map(lambda instance: build(instance, args.generate_only), instances))
    report = HERE / ('build_validation.json' if not args.models else 'build_validation_selected.json')
    report.write_text(json.dumps({'pass': True, 'models': results}, indent=2) + '\n')


if __name__ == '__main__':
    main()
