#!/usr/bin/env python3
"""Refresh the self-contained PE snapshot from an explicitly selected wrapper.

This manual import step reads AdaptNIC. Normal build.py and gem5 runs require
only Naviq. Paths and SHA-256 hashes in SOURCES.json record exact provenance.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import sys


HERE = Path(__file__).resolve().parent
NAVI = HERE.parents[4]
BASE = 0x20200000000
STRIDE = 0x100000
PE_NAMES = (
    "aes_tx_0", "aes_rx_0", "aes_tx_1", "aes_rx_1", "checksum_normal",
    "checksum_verify", "multicast", "overloaded_nat", "packet_rate_limiter",
    "telemetry", "uro", "uso", "dummy_loopback")
DIRECT_PE_PORTS = {
    "uso": ("u_packet_in_nsu", "packet_in_local", "nsu"),
    "uro": ("u_packet_out_nmu", "packet_out_local", "nmu"),
}
AXIS_SIGNALS = (("tdata", 512), ("tkeep", 64), ("tid", 6),
                ("tdest", 10), ("tlast", 1), ("tvalid", 1), ("tready", 1))
LOCAL_AXIS_SIGNALS = (*AXIS_SIGNALS, ("tuser", 1))


def write_if_changed(path: Path, content: bytes | str):
    if isinstance(content, str):
        content = content.encode()
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_bytes() != content:
        path.write_bytes(content)


def write_json(path, value):
    write_if_changed(path, json.dumps(value, indent=2) + "\n")


def sv_value(value):
    if isinstance(value, (bool, int)):
        return int(value)
    text = str(value).strip()
    match = re.fullmatch(r"(?:\d+)?'[sS]?([bBdDhH])([0-9a-fA-F_]+)", text)
    if match:
        return int(match[2].replace("_", ""), {"b": 2, "d": 10, "h": 16}[match[1].lower()])
    try:
        return int(text, 0)
    except ValueError:
        return text


def flat_declarations(prefix, ingress):
    result = []
    for signal, width in LOCAL_AXIS_SIGNALS:
        direction = "input" if ingress != (signal == "tready") else "output"
        bits = f" [{width - 1}:0]" if width > 1 else ""
        result.append(f"    {direction} logic{bits} {prefix}_{signal}")
    return result


def axis_interface(name, array=""):
    return ("    ifc_axis #(.DATA_WIDTH(512), .TDEST_WIDTH(10), .TID_WIDTH(6),\n"
            f"        .TUSER_WIDTH(1)) {name}{array} (.axis_aclk(clk));")


def flat_connections(prefix, interface, ingress):
    result = []
    for signal, _ in LOCAL_AXIS_SIGNALS:
        member = signal if signal in ("tvalid", "tready") else "t." + {
            "tdata": "data", "tkeep": "keep", "tid": "id", "tdest": "dest",
            "tlast": "last", "tuser": "user"}[signal]
        left, right = f"{interface}.{member}", f"{prefix}_{signal}"
        if ingress == (signal == "tready"):
            left, right = right, left
        result.append(f"    assign {left} = {right};")
    return result


def pe_harness(name, wrapper_module, rtl_port, role):
    lines = ["// Generated by sync_snapshot.py. The PE wrapper is unchanged.",
             '`include "ifc_axis.sv"', f"module pe13_{name}_sim (",
             ",\n".join(["    input logic clk", "    input logic resetn",
                          *flat_declarations("local", role == "nsu")]), ");",
             axis_interface("local_axis"),
             *flat_connections("local", "local_axis", role == "nsu"),
             f"    {wrapper_module} u_dut (",
             "        .clk(clk), .resetn(resetn),",
             f"        .{rtl_port}(local_axis)", "    );", "endmodule", ""]
    return "\n".join(lines)


def xpm_boundary(name, interface, role):
    kind, signal_prefix = ("nmu", "s_axis") if role == "nmu" else ("nsu", "m_axis")
    lines = [f"    xpm_{kind}_strm #(.DATA_WIDTH(512), .DST_ID_WIDTH(10),",
             f"        .ID_WIDTH(6), .NOC_FABRIC(\"VNOC\")) u_{name}_{kind} ("]
    ports = [f"        .{signal_prefix}_aclk(clk)"]
    for signal, _ in AXIS_SIGNALS:
        member = signal if signal in ("tvalid", "tready") else "t." + {
            "tdata": "data", "tkeep": "keep", "tid": "id", "tdest": "dest",
            "tlast": "last"}[signal]
        ports.append(f"        .{signal_prefix}_{signal}({interface}.{member})")
    if role == "nmu":
        ports.append("        .dst_id_err()")
    lines += [",\n".join(ports), "    );"]
    if role == "nsu":
        lines.append(f"    assign {interface}.t.user = '0;")
    return lines


def host_harness():
    direct = [("generator0", True), ("generator1", True), ("sink0", False),
              ("uso", False), ("uro", True)]
    lines = ["// Generated by sync_snapshot.py. Host fabric RTL is unchanged.",
             "// Two packet producers model traffic offered to the one host H2C bus.",
             "// One checker consumes the physical host C2H bus.",
             '`include "ifc_axis.sv"', "module pe13_host_fabric_sim (",
             ",\n".join(["    input logic clk", "    input logic resetn",
                          *(port for name, ingress in direct
                            for port in flat_declarations(name, ingress))]), ");",
             axis_interface("generator_axis", " [2]"), axis_interface("h2c_axis"),
             axis_interface("c2h_axis"), axis_interface("uso_axis"), axis_interface("uro_axis"),
             axis_interface("noc_h2c", " [2]"), axis_interface("noc_c2h", " [2]")]
    for name, interface, ingress in (
            ("generator0", "generator_axis[0]", True),
            ("generator1", "generator_axis[1]", True),
            ("sink0", "c2h_axis", False), ("uso", "uso_axis", False),
            ("uro", "uro_axis", True)):
        lines += flat_connections(name, interface, ingress)
    lines += ["    axis_packet_arbiter #(",
              "        .DATA_WIDTH(512), .TDEST_WIDTH(10), .TID_WIDTH(6),",
              "        .TUSER_WIDTH(1), .NUM_SLAVES(2), .REGISTER_GRANT(1'b1)",
              "    ) u_test_producer_merge (",
              "        .clk(clk), .resetn(resetn),",
              "        .s_axis(generator_axis), .m_axis(h2c_axis)", "    );",
              "    host_packet_fabric #(",
              "        .HOST_NOC_LANES(2), .USO_LOCAL_TDEST(14), .HOST_TID_BASE(26),",
              "        .NUM_SOURCES(32), .MAX_PACKET_SIZE_BYTES(2048)",
              "    ) u_host_fabric (",
              "        .clk(clk), .resetn(resetn), .s_axis_h2c(h2c_axis),",
              "        .m_axis_uso(uso_axis), .s_axis_uro(uro_axis),",
              "        .m_axis_noc_h2c(noc_h2c), .s_axis_noc_c2h(noc_c2h),",
              "        .m_axis_c2h(c2h_axis)", "    );"]
    for lane in range(2):
        lines += xpm_boundary(f"h2c_{lane}", f"noc_h2c[{lane}]", "nmu")
        lines += xpm_boundary(f"c2h_{lane}", f"noc_c2h[{lane}]", "nsu")
    return "\n".join([*lines, "endmodule", ""])


def endpoint(component, name, role, *, transport="noc", instance_path=None, rtl_port=None):
    value = {"name": name, "instance_path": instance_path or name,
             "protocol": "axis", "role": role, "transport": transport,
             "connections": [{"connect_to": f"{component}.{name}",
                              "connect_loc": 0, "clock_domain": 400}]}
    if rtl_port:
        value["rtl_port"] = rtl_port
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adapt-nic-root", type=Path, required=True)
    parser.add_argument("--wrapper-manifest", type=Path, required=True)
    args = parser.parse_args()
    root = args.adapt_nic_root.resolve()
    manifest_path = args.wrapper_manifest.resolve()
    if not manifest_path.is_relative_to(root):
        parser.error("Wrapper manifest must be inside the specified AdaptNIC root")
    spec = importlib.util.spec_from_file_location("pe13_ip_manifests", root / "ip/scripts/gen_ip_make.py")
    registry = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(registry)
    manifests = registry.collect_manifests(root / "ip")
    wrapper = json.loads(manifest_path.read_text())
    import yaml
    inputs_path = root / wrapper["inputs"]["instances"]
    inputs = yaml.safe_load(inputs_path.read_text())
    configured = {item["name"]: item for item in inputs["instances"]}
    generated = {item["name"]: item for item in wrapper["instances"]}
    if set(configured) != set(PE_NAMES) or set(generated) != set(PE_NAMES):
        parser.error("The selected wrapper must contain exactly the 13 configured PEs")
    if (wrapper.get("host_noc_lanes") != 2 or
            generated["uso"].get("host_attachment") != "uso" or
            generated["uro"].get("host_attachment") != "uro"):
        parser.error("Select the generated wrapper with two host lanes and host-local USO/URO")
    previous_instances = {item["name"]: item for item in json.loads((HERE / "instances.json").read_text())}
    old_sources = json.loads((HERE / "SOURCES.json").read_text())
    origins = {}

    def take(source):
        source = Path(source).resolve()
        if not source.is_file() or not source.is_relative_to(root):
            raise ValueError(f"Canonical source is missing/outside AdaptNIC: {source}")
        relative = source.relative_to(root).as_posix()
        destination = "snapshot/" + relative
        content = source.read_bytes()
        write_if_changed(HERE / destination, content)
        origins[destination] = {"source": relative, "sha256": hashlib.sha256(content).hexdigest()}
        return destination

    def sources_for(ip_ids):
        dependencies = []
        for ip_id in ip_ids:
            for dependency in registry.closure(ip_id, manifests):
                if dependency not in dependencies:
                    dependencies.append(dependency)
        sources, includes = [], []
        for dependency in dependencies:
            info = manifests[dependency]
            for source in info["rtl_sources"]:
                copied = take(source)
                if copied not in sources:
                    sources.append(copied)
                if str(Path(copied).parent) not in includes:
                    includes.append(str(Path(copied).parent))
            for header in info["rtl_headers"]:
                # Packet-engine manifests list a testbench-only shared header.
                if header.name == "packet_engine_harness.svh":
                    continue
                copied = take(header)
                if str(Path(copied).parent) not in includes:
                    includes.append(str(Path(copied).parent))
            take(info["manifest"])
        return sources, includes

    def spec_for(instance, sources, includes, top):
        return {
            "schema_version": 1, "design": "pe13_" + instance["name"], "top_module": top,
            "sources": [*sources, "sim/xpm_cdc_async_rst.sv", "../../include/xpm_nsu_strm.sv",
                        "../../include/xpm_nmu_strm.sv", "../../include/xpm_nsu_mm.sv"],
            "include_dirs": includes,
            "extra_args": ["--output-split", "20000", "--output-split-cfuncs", "10000"],
            "endpoints": [copy.deepcopy(port) for port in instance["endpoints"]
                          if port.get("transport", "noc") == "noc"],
        }

    instances = []
    for index, name in enumerate(PE_NAMES):
        canonical = generated[name]
        item = copy.deepcopy(configured[name])
        item["packet_engine"] = canonical["packet_engine"].split("/")[-1]
        item["parameters"] = {key: sv_value(value) for key, value in canonical["parameters"].items()}
        expected = {"OFFLOAD_ID": index, "TID_BASE": 2 * index, "AXIS_DATA_WIDTH": 512,
                    "REBUILD_PACKETS": 1, "NUM_SOURCES": 32, "MAX_PACKET_SIZE_BYTES": 2048,
                    "NUM_FLOWS": 4096, "STEERING_MODE": 0}
        for key, value in expected.items():
            if item["parameters"].get(key) != value:
                raise ValueError(f"{name}: expected {key}={value}, got {item['parameters'].get(key)}")
        if item["control_aperture"] != {"start": BASE + index * STRIDE, "size": STRIDE}:
            raise ValueError(f"{name}: unexpected control aperture")
        item["endpoints"] = copy.deepcopy(previous_instances[name]["endpoints"])
        direct = DIRECT_PE_PORTS.get(name)
        for port in item["endpoints"]:
            # Names/order are stable logical aliases. Hierarchy may change when
            # the simulation top supplies a plain-signal direct AXIS boundary.
            port.pop("rtl_port", None)
            port["transport"] = "noc"
            port["instance_path"] = port["name"]
            if direct:
                if port["name"] == direct[0]:
                    port.update(transport="direct", rtl_port=direct[1], flat_prefix="local")
                else:
                    port["instance_path"] = "u_dut." + port["name"]
        sources, includes = sources_for([canonical["packet_engine"]])
        source = take(root / canonical["source"])
        sources.append(source)
        includes.append(str(Path(source).parent))
        top = canonical["module"]
        if direct:
            harness = f"sim/{name}_sim.sv"
            write_if_changed(HERE / harness, pe_harness(name, top, direct[1], direct[2]))
            sources.append(harness)
            top = f"pe13_{name}_sim"
        write_json(HERE / f"{name}.rtl.json", spec_for(item, sources, includes, top))
        instances.append(item)

    host = {"name": "host_fabric", "module": "host_packet_fabric", "parameters": {
        "HOST_NOC_LANES": 2, "USO_LOCAL_TDEST": 14, "HOST_TID_BASE": 26,
        "NUM_SOURCES": 32, "MAX_PACKET_SIZE_BYTES": 2048}, "endpoints": []}
    for name, role in (("h2c_0", "nmu"), ("h2c_1", "nmu"), ("c2h_0", "nsu"), ("c2h_1", "nsu")):
        host["endpoints"].append(endpoint("host_fabric", name, role, instance_path=f"u_{name}_{role}"))
    for name, role in (("generator0", "nsu"), ("generator1", "nsu"), ("sink0", "nmu"),
                       ("uso", "nmu"), ("uro", "nsu")):
        port = endpoint("host_fabric", name, role, transport="direct", rtl_port=name)
        port["flat_prefix"] = name
        host["endpoints"].append(port)
    sources, includes = sources_for(["lib/axis/axis_demux", "lib/axis/axis_packet_arbiter",
                                     "lib/axis/axis_packet_rebuilder", "lib/axis/axis_register_slice"])
    sources.append(take(root / "smartnic/smartnic_core/host_subsystem/host_packet_fabric.sv"))
    write_if_changed(HERE / "sim/host_fabric_sim.sv", host_harness())
    sources.append("sim/host_fabric_sim.sv")
    write_json(HERE / "host_fabric.rtl.json", spec_for(host, sources, includes, "pe13_host_fabric_sim"))
    write_json(HERE / "host_fabric.instance.json", host)
    take(manifest_path)
    take(inputs_path)
    write_json(HERE / "instances.json", instances)
    write_json(HERE / "SOURCES.json", dict(sorted(origins.items())))
    write_json(HERE / "SNAPSHOT.json", {
        "version": 1, "wrapper_manifest": manifest_path.relative_to(root).as_posix(),
        "wrapper_sha256": hashlib.sha256(manifest_path.read_bytes()).hexdigest(),
        "generated_by": "sync_snapshot.py", "pe_count": 13, "models": 14,
        "pe_control_apertures": 13, "pe_axis_ports": 33, "pe_direct_axis_ports": 2,
        "host_noc_axis_ports": 4, "host_direct_axis_ports": 5,
    })
    # Prune only files recorded as owned by the previous imported snapshot.
    for stale in sorted(set(old_sources) - set(origins)):
        path = (HERE / stale).resolve()
        if path.is_relative_to(HERE / "snapshot") and path.is_file():
            path.unlink()
    print(f"Imported 13 PEs and host fabric: {len(origins)} canonical files; no build depends on AdaptNIC")


if __name__ == "__main__":
    main()
